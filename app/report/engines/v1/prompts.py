"""V1 Map(근거 카드) 지시문. 중괄호를 쓰지 않는다(ADK 상태 치환 방지)."""


def map_instruction(author_name: str) -> str:
    return f"""너는 코드 리뷰어다. 입력은 개발자 "{author_name}"의 커밋 일부와 그 diff다. diff에서 확인되는 사실만으로 근거 카드를 만든다.
입력 형식: '### C3 | 날짜 | 커밋 메시지' 아래에 파일별 diff가 온다. '--- [F12] 경로'처럼 ID가 붙은 파일만 근거로 쓸 수 있다. 'HEAD에 없음' 파일은 지금 레포에 없으므로 근거가 될 수 없다.
규칙:
- features(최대 8개): 이 diff에서 작성자가 만들거나 바꾼 기능 단위. 사용자나 시스템 관점의 동작으로 적는다.
  - name: 짧은 기능명(예: JWT 로그인 API, 워크스페이스 설정 모달).
  - summary: 코드가 실제로 하는 일 1~2문장. diff에 보이는 함수, 컴포넌트, 훅, 라이브러리 이름을 넣는다. diff에 없는 동작(재시도, 회전, 캐싱, 성능 수치 등)을 추측해서 쓰지 않는다.
  - file_ids: 그 기능의 근거 파일 ID. commit_ids: 근거 커밋 ID.
  - level_hint: created(새로 만듦), major(크게 바꿈), minor(일부 수정, 버그 수정, 스타일).
- 설정 파일만 바뀐 커밋, 이름 변경, 포매팅은 기능으로 만들지 않는다.
- patterns(최대 4개): diff에서 보이는 설계·구현 패턴. 근거 파일 ID를 문장에 함께 쓴다(예: F3에서 React Query로 서버 상태를 관리).
- risks(최대 4개): diff에서 실제로 보이는 문제나 개선 여지. 근거 파일 ID를 함께 쓴다. 없으면 빈 배열.
- notes(최대 3개): 그 밖에 기능 판단에 필요한 관찰(예: 다른 사람이 만든 화면에 API 연결만 함).
모든 값은 한국어로 쓴다."""
